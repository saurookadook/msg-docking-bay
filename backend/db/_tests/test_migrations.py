from alembic import command
from alembic.script import ScriptDirectory

from conftest import alembic_config


class TestMigrations:
    def test_has_one_head(self) -> None:
        """Two heads mean two branches need a merge (ALEM-10)."""
        script = ScriptDirectory.from_config(alembic_config())

        assert len(script.get_heads()) == 1

    def test_downgrade_and_upgrade_round_trip(self) -> None:
        """A downgrade that leaves an object behind breaks the upgrade
        (ALEM-8, ALEM-14).
        """
        config = alembic_config()

        command.downgrade(config, "base")
        command.upgrade(config, "head")

    def test_models_match_the_migrated_schema(self) -> None:
        """A model change without its migration fails here (ALEM-14).

        ``command.check`` raises ``AutogenerateDiffsDetected`` when
        autogenerate would write a new revision. It shares
        autogenerate's blind spots (ALEM-6), so review still matters.
        The repo has no CI workflow yet, so the suite runs it.
        """
        command.check(alembic_config())
